//    Why:  the three pages, as pure string functions: README (the map), one page per sprint, one per task.
//          Links point at the real source files relative to the page, so the markdown preview opens them.
import * as posix from 'node:path/posix';
import type { DocSprint, DocTask, DocsModel } from './model';

export const BANNER = (date: string): string =>
  `<!-- generated by Orqiva on ${date}; do not edit -->`;

export const README_FILE = 'README.md';
export const sprintFile = (code: string): string => `sprints/${code}.md`;
export const taskFile = (ref: string): string => `tasks/${ref}.md`;

/** link between two pages of the output folder (both paths relative to that folder) */
export function linkInside(pageRel: string, targetRel: string): string {
  return posix.relative(posix.dirname(pageRel), targetRel) || targetRel;
}

// ── [PCODE-41 | S08 | v0.1.0] linkToSource: the page sits at <outFolder>/<pageRel>, the file at the repo root ──
export function linkToSource(
  outFolder: string,
  pageRel: string,
  fileRel: string,
  line?: number,
): string {
  const from = posix.dirname(posix.join(outFolder, pageRel));
  const rel = posix.relative(from, fileRel) || fileRel;
  return line ? `${rel}#L${String(line)}` : rel;
}

function table(header: string[], rows: string[][]): string[] {
  if (!rows.length) return [];
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ];
}

const escape = (s: string): string => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();

// ── [PCODE-41 | S08 | v0.1.0] renderReadme: project, version, the sprint table, the totals ──
export function renderReadme(model: DocsModel): string {
  const lines = [
    BANNER(model.generatedAt),
    '',
    `# ${model.project.name} — code documentation`,
    '',
    `Project \`${model.project.identifier}\` · version ${model.project.version} · generated ${model.generatedAt}`,
    '',
    `${String(model.hits)} fingerprint(s) from ${String(model.tasks.length)} task(s), across ${String(model.files)} scanned file(s).`,
    '',
    '## Sprints',
    '',
    ...table(
      ['Sprint', 'Date', 'Done', 'Goal'],
      model.sprints.map((s) => [
        `[${s.code} ${escape(s.name)}](${sprintFile(s.code)})`,
        s.date || '—',
        `${String(s.done)}/${String(s.total)}`,
        escape(s.goal) || '—',
      ]),
    ),
    '',
    '## Tasks',
    '',
    ...table(
      ['Task', 'Title', 'State', 'Sprint', 'Files'],
      model.tasks.map((t) => [
        `[${t.ref}](${taskFile(t.ref)})`,
        escape(t.title),
        escape(t.state),
        t.sprints.join(', ') || '—',
        String(t.files.length),
      ]),
    ),
    '',
    `Written from the fingerprint markers in the code (\`${model.outFolder}\`); \`orq done\` keeps them in step with Orqiva.`,
  ];
  return `${lines.join('\n')}\n`;
}

// ── [PCODE-41 | S08 | v0.1.0] renderSprint: the sprint's goal and every task with its files ──
export function renderSprint(model: DocsModel, sprint: DocSprint): string {
  const page = sprintFile(sprint.code);
  const lines = [
    BANNER(model.generatedAt),
    '',
    `# ${sprint.code} — ${sprint.name}`,
    '',
    `${sprint.date || 'no date'} · ${String(sprint.done)}/${String(sprint.total)} done · [all sprints](${linkInside(page, README_FILE)})`,
    '',
  ];
  if (sprint.goal) lines.push(`> ${sprint.goal}`, '');
  for (const ref of sprint.tasks) {
    const task = model.tasks.find((t) => t.ref === ref);
    if (!task) {
      lines.push(`## ${ref}`, '', '_No fingerprinted code yet._', '');
      continue;
    }
    lines.push(
      `## [${task.ref}](${linkInside(page, taskFile(task.ref))}) ${task.title}`,
      '',
      `${task.state} · ${task.priority}${task.labels.length ? ` · ${task.labels.join(', ')}` : ''}${task.versions.length ? ` · v${task.versions.join(', v')}` : ''}`,
      '',
    );
    if (task.files.length) {
      for (const f of task.files)
        lines.push(
          `- \`${f.file}\` — ${f.lines.map((l) => `[${String(l)}](${linkToSource(model.outFolder, page, f.file, l)})`).join(', ')}`,
        );
    } else {
      lines.push('_No fingerprinted code yet._');
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

// ── [PCODE-41 | S08 | v0.1.0] renderTask: description, acceptance, the code it wrote, the Plane comments ──
export function renderTask(model: DocsModel, task: DocTask): string {
  const page = taskFile(task.ref);
  const lines = [
    BANNER(model.generatedAt),
    '',
    `# ${task.ref} — ${task.title}`,
    '',
    [
      task.state,
      task.priority,
      task.sprints.join(', ') || null,
      task.versions.length ? `v${task.versions.join(', v')}` : null,
      task.labels.length ? task.labels.join(', ') : null,
    ]
      .filter(Boolean)
      .join(' · '),
    '',
  ];
  if (task.detail.url) lines.push(`[Open in Orqiva](${task.detail.url})`, '');
  if (task.offline)
    lines.push('_Task details unavailable — this page was written from the code alone._', '');
  if (task.detail.description) lines.push('## Description', '', task.detail.description.trim(), '');
  if (task.detail.acceptance?.length) {
    lines.push('## Acceptance', '');
    for (const a of task.detail.acceptance) lines.push(`- [${a.done ? 'x' : ' '}] ${a.text}`);
    lines.push('');
  }
  lines.push('## Code', '');
  if (task.files.length) {
    for (const f of task.files) {
      const links = f.lines
        .map((l) => `[${String(l)}](${linkToSource(model.outFolder, page, f.file, l)})`)
        .join(', ');
      lines.push(`- \`${f.file}\` — ${links}${f.header ? ' (header)' : ''}`);
    }
  } else {
    lines.push('_No fingerprinted code yet._');
  }
  lines.push('');
  if (task.detail.comments?.length) {
    lines.push('## History', '');
    for (const c of task.detail.comments)
      lines.push(`- **${c.kind}** ${c.date}${c.who ? ` · ${c.who}` : ''} — ${escape(c.text)}`);
    lines.push('');
  }
  lines.push(`[← ${model.project.identifier} documentation](${linkInside(page, README_FILE)})`);
  return `${lines.join('\n').trimEnd()}\n`;
}
