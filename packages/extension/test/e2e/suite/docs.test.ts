// ── [PCODE-192 | S15 | v0.1.0] Rebrand ProdEngine and PlaneCode to Orqiva everywhere, with compatibility for existing installs ──
// ── [PCODE-44 | S08 | v0.1.0] Add an e2e test generating docs in the fixture workspace ──
//    Why:  the command in the real host: it writes the three page kinds into the fixture, the Docs view shows
//          them under "Generated docs", and the workspace is left as it was found.
import * as assert from 'node:assert/strict';
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as vscode from 'vscode';

interface DocNodeLike {
  kind: string;
  folder?: string;
  name?: string;
  entry?: { key: string };
}
interface Api {
  getDocsTree(): { getChildren(node?: DocNodeLike): DocNodeLike[] } | undefined;
}

describe('code documentation (e2e)', () => {
  const folder = vscode.workspace.workspaceFolders?.[0]?.uri.fsPath ?? '';
  const out = path.join(folder, 'docs', 'generated');
  const config = () => vscode.workspace.getConfiguration('orqiva');

  before(async () => {
    // the fixture has no Plane behind it: generate the pages, do not comment on anything
    // Global lands in the throwaway test profile, not in the fixture's .vscode folder
    await config().update('docs.postToPlane', false, vscode.ConfigurationTarget.Global);
  });
  after(async () => {
    await config().update('docs.postToPlane', undefined, vscode.ConfigurationTarget.Global);
    fs.rmSync(path.join(folder, 'docs'), { recursive: true, force: true });
  });

  // ── [PCODE-44 | S08 | v0.1.0] README, one sprint page and one task page, with their headings ──
  it('writes README, sprints and tasks into docs/generated', async () => {
    await vscode.commands.executeCommand('orqiva.generateDocs');
    const readme = path.join(out, 'README.md');
    assert.ok(fs.existsSync(readme), 'README.md missing');
    const text = fs.readFileSync(readme, 'utf8');
    assert.match(
      text.split('\n')[0] ?? '',
      /^<!-- generated by Orqiva on \d{4}-\d{2}-\d{2}; do not edit -->$/,
    );
    assert.match(text, /# Fixture Project — code documentation/);
    assert.match(text, /## Sprints/);
    assert.match(text, /\[S01 Sprint 01 - Foundation\]\(sprints\/S01\.md\)/);

    const sprint = fs.readFileSync(path.join(out, 'sprints', 'S01.md'), 'utf8');
    assert.match(sprint, /# S01 — Sprint 01 - Foundation/);
    assert.match(sprint, /\[FIX-2\]\(\.\.\/tasks\/FIX-2\.md\)/);

    const task = fs.readFileSync(path.join(out, 'tasks', 'FIX-2.md'), 'utf8');
    assert.match(task, /# FIX-2 — Add the greeting function/);
    assert.match(task, /## Code/);
    // the link climbs out of docs/generated/tasks and points at the real file and line
    assert.match(task, /\(\.\.\/\.\.\/\.\.\/src\/sample\.ts#L2\)/);
    assert.ok(fs.existsSync(path.join(folder, 'src', 'sample.ts')));
  });

  it('shows the pages in the Docs view without a manual refresh', async () => {
    const ext = vscode.extensions.getExtension<Api>('broszio.orqiva');
    assert.ok(ext);
    const api = await ext.activate();
    const tree = api.getDocsTree();
    assert.ok(tree, 'docs tree missing');
    const generated = tree.getChildren().find((n) => n.kind === 'generated');
    assert.ok(generated, 'Generated docs node missing');
    const children = tree.getChildren(generated);
    assert.deepEqual(children.map((c) => c.name ?? c.folder).sort(), [
      'README.md',
      'sprints',
      'tasks',
    ]);
  });
});
