/** The server, not yet listening, so tests can pick a free port. */
export function createApp(opts: AppOptions = {}): HttpServer {
  const { auth, webDir, live, ...http } = opts;
  const gateway =
    live && auth
      ? new LiveGateway({
          pool: auth.pool,
          bus: live.bus,
          allowedOrigins: live.allowedOrigins,
          ...(live.presence ? { presence: live.presence } : {}),
          ...(live.chat ? { chat: live.chat } : {}), // [PCODE-234 | S15 | v0.1.0]
          ...(live.ws ? { ws: live.ws } : {}),
        })
      : null;
  // [PCODE-108 | S15 | v0.1.0] Git host webhooks need the raw body, so they run before the JSON router
  // [PCODE-304 | S15 | v0.1.0] pull requests a webhook changed get the merge policy's verdict posted
  const hooks = auth
    ? gitWebhooks(
        auth.pool,
        (m, d) => opts.logger?.error(m, d),
        policyAfterDeliveries(auth.pool, {
          ...(auth.publicUrl ? { publicUrl: auth.publicUrl } : {}),
          log: (m, d) => opts.logger?.error(m, d),
        }),
      )
    : null;
  // [PCODE-246 | S15 | v0.1.0] an outside system starts an agent through its own webhook
  const agentHooks = auth ? agentWebhooks(auth.pool, (m, d) => opts.logger?.error(m, d)) : null;
  const stream = gateway?.handleStream;
  // [PCODE-168 | S15 | v0.1.0] uploads stream their bytes, so they also run before the JSON router
  const uploads = auth ? fileUploads(auth.pool, blobStoreOf(auth)) : null;
  const raw =
    hooks || stream || uploads
      ? (req: IncomingMessage, res: ServerResponse): boolean =>
          (hooks?.(req, res) ?? false) ||
          (agentHooks?.(req, res) ?? false) ||
          (uploads?.(req, res) ?? false) ||
          (stream?.(req, res) ?? false)
      : undefined;
  const server = createHttpServer({
    routes: buildRoutes(auth),
    ...(raw ? { raw } : {}),
    ...http,
    ...(webDir && existsSync(webDir) ? { fallback: staticFiles(webDir) } : {}),
    ...(gateway
      ? {
          beforeClose: () => {
            gateway.close();
          },
        }
      : {}),
  });
  if (gateway) server.server.on('upgrade', gateway.handleUpgrade);
  return server;
}
