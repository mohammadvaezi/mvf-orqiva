// [PCODE-168 | S15 | v0.1.0] one store per data directory (tests without one share a temporary folder)
const stores = new Map<string, BlobStore>();
function blobStoreOf(auth: AuthDeps): BlobStore {
  const dir = auth.dataDir ?? join(tmpdir(), 'orqiva-data');
  let s = stores.get(dir);
  if (!s) {
    s = new BlobStore(dir);
    stores.set(dir, s);
  }
  return s;
}

