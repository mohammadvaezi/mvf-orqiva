import { parseColor, parsePx } from './designtokens.js';
import { aliasOf, tokenResolver, type DesignToken, type TokenTheme } from './docs.js';
import { A11Y_RULE } from './a11y.js'; // [PCODE-296 | S15 | v0.1.0]

/** Files whose text can hold UI: style sheets, markup and components. */
export const isUiFile = (path: string): boolean =>
  /\.(css|scss|sass|less|tsx|jsx|vue|svelte|html|astro)$/i.test(path) &&
  !/(^|\/)(node_modules|dist|build|out|coverage|vendor)\//.test(path) &&
  !/\.min\.(css|js)$/i.test(path);

/** Files the kit wrote itself (token exports) are not checked. */
export const isGenerated = (text: string): boolean =>
  /generated by Orqiva\. Do not edit by hand/.test(text.slice(0, 400));

const esc = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** How often each component appears as a tag (<Button …, <Button>, <Button/>) in a text. */
export function componentUses(text: string, names: readonly string[]): Map<string, number> {
  const out = new Map<string, number>();
  for (const name of names) {
    if (!/^[A-Z][A-Za-z0-9.]*$/.test(name)) continue;
    const n = text.match(new RegExp('<' + esc(name) + '(?=[\\s/>])', 'g'))?.length ?? 0;
    if (n) out.set(name, n);
  }
  return out;
}

export interface KitFinding {
  path: string;
  line: number;
  kind: 'colour' | 'size';
  value: string;
  /** the token with the same value, if one exists */
  token: string | null;
}

const SIZE_PROPS =
  '(?:row-gap|column-gap|font-size|border-radius|gap|' +
  'margin(?:-(?:top|right|bottom|left|inline|block))?|padding(?:-(?:top|right|bottom|left|inline|block))?|' +
  'margin(?:Top|Right|Bottom|Left)|padding(?:Top|Right|Bottom|Left)|' +
  'fontSize|borderRadius|rowGap|columnGap)';
const SIZE = new RegExp('\\b' + SIZE_PROPS + '\\s*[:=]\\s*[\'"`]?([^;\'"`}\\n]*)', 'g');
const COLOUR = /#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch)\([^)\n]*\)/g;

const colourKey = (v: string): string | null => {
  const c = parseColor(v);
  if (!c) return null;
  return c.slice(0, 3).join(',') + ',' + String(Math.round(c[3] * 100));
};

export interface TokenIndex {
  colours: Map<string, string>;
  sizes: Map<number, string>;
}

/** The tokens' final values: a colour or a px size to the token name to suggest for it. */
export function tokenIndex(
  tokens: readonly DesignToken[],
  themes: readonly TokenTheme[] = [],
): TokenIndex {
  const read = tokenResolver(tokens, themes);
  const colours = new Map<string, string>();
  const sizes = new Map<number, string>();
  // a token that points at another is the meaning (color.brand), so it is named before the raw one
  const order = [...tokens].sort(
    (a, b) =>
      Number(aliasOf(b.valueLight) !== null) - Number(aliasOf(a.valueLight) !== null) ||
      a.name.localeCompare(b.name),
  );
  for (const t of order) {
    const v = read(t.name, 'light');
    if (v === null) continue;
    if (t.type === 'color') {
      const k = colourKey(v);
      if (k && !colours.has(k)) colours.set(k, t.name);
    } else if (t.type === 'dimension') {
      const px = parsePx(v);
      if (px !== null && !sizes.has(px)) sizes.set(px, t.name);
    }
  }
  return { colours, sizes };
}

/** Colours, and sizes of spacing, radius and font size, written by hand in a file. Lines that sit in
 *  a comment or say kit-ignore are left alone; values in var(), calc() or a template are not raw;
 *  0 and 1px (hairlines) are allowed. */
export function lintKit(path: string, text: string, index: TokenIndex): KitFinding[] {
  if (!isUiFile(path) || isGenerated(text)) return [];
  const out: KitFinding[] = [];
  let inComment = false;
  text.split('\n').forEach((raw, i) => {
    let line = raw;
    if (inComment) {
      const end = line.indexOf('*/');
      if (end < 0) return;
      line = line.slice(end + 2);
      inComment = false;
    }
    line = line.replace(/\/\*.*?\*\//g, '').replace(/<!--.*?-->/g, '');
    const open = line.indexOf('/*');
    if (open >= 0) {
      inComment = true;
      line = line.slice(0, open);
    }
    if (/^\s*\/\//.test(line) || raw.includes('kit-ignore')) return;
    const code = line.replace(/https?:\/\/\S+/g, '');
    for (const m of code.matchAll(COLOUR)) {
      const v = m[0];
      // an id selector (#main {) is not a colour, and hex has 3, 4, 6 or 8 digits
      if (v.startsWith('#') && /^#[0-9a-fA-F]+\s*[{,]/.test(code.slice(m.index))) continue;
      if (v.startsWith('#') && ![4, 5, 7, 9].includes(v.length)) continue;
      const k = colourKey(v);
      if (!k) continue;
      out.push({
        path,
        line: i + 1,
        kind: 'colour',
        value: v,
        token: index.colours.get(k) ?? null,
      });
    }
    for (const m of code.matchAll(SIZE)) {
      const value = (m[1] ?? '').trim();
      if (!value || /var\(|\$|calc\(|theme\(|\{/.test(value)) continue;
      for (const part of value.split(/\s+/)) {
        if (!/^-?\d*\.?\d+(px|rem)$/.test(part)) continue;
        const n = parsePx(part);
        if (n === null || Math.abs(n) <= 1) continue;
        out.push({
          path,
          line: i + 1,
          kind: 'size',
          value: part,
          token: index.sizes.get(Math.abs(n)) ?? null,
        });
      }
    }
  });
  return out;
}

/** The rule agents get when they write UI in a project with a kit. */
export function kitRule(
  tokens: readonly DesignToken[],
  components: readonly { name: string; codePath: string; status: string }[],
  max = 3500,
): string {
  if (!tokens.length && !components.length) return '';
  const parts: string[] = [
    'UI kit rule: generated UI uses the project’s design tokens and components. Write colours, spacing, radii and font sizes as the tokens below (in CSS as var(--name-with-dashes), or from the exported token files), never as raw values; use the listed components instead of writing new ones; when something is missing, say so instead of inventing a value. `orq kit check` lists raw values in changed files.',
    // [PCODE-296 | S15 | v0.1.0] before the tokens, so a long token list never cuts it off
    A11Y_RULE + ' `orq a11y check` lists problems in changed files.',
  ];
  const live = components.filter((c) => c.status !== 'deprecated');
  if (live.length)
    parts.push(
      'Components: ' +
        live.map((c) => c.name + (c.codePath ? ' (' + c.codePath + ')' : '')).join(', ') +
        '.',
    );
  const gone = components.filter((c) => c.status === 'deprecated');
  if (gone.length)
    parts.push('Deprecated, do not use: ' + gone.map((c) => c.name).join(', ') + '.');
  if (tokens.length)
    parts.push('Tokens: ' + tokens.map((t) => t.name + ' ' + t.valueLight).join('; ') + '.');
  const text = parts.join('\n');
  return text.length > max ? text.slice(0, max - 1) + '…' : text;
}
