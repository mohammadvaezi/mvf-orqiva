// ── [PCODE-290 | S15 | v0.1.0] T30.4 UI kit in the code: component usage, a lint for non-token values, the agent rule ──
//    Why:  components are counted as tags only; raw colours and sizes are found with the token that
//          has the same value, while comments, var(), id selectors, hairlines and the kit's own files
//          stay quiet; the rule names what agents must use.
import { describe, expect, it } from 'vitest';
import { componentUses, kitRule, lintKit, tokenIndex, type DesignToken } from '../src/index.js';

const tok = (name: string, type: string, valueLight: string): DesignToken => ({
  name,
  type,
  valueLight,
  valueDark: '',
  description: '',
});
const tokens = [
  tok('color.primary', 'color', '#4F46E5'),
  tok('color.brand', 'color', '{color.primary}'),
  tok('space.4', 'dimension', '1rem'),
  tok('radius.md', 'dimension', '6px'),
];

describe('component usage', () => {
  it('counts tags, not words or longer names', () => {
    const text =
      'import { Button } from "./ui";\n<Button kind="primary">Go</Button>\n<Button/>\n<ButtonGroup>\n<Card.Header>';
    expect([...componentUses(text, ['Button', 'Card.Header', 'Chip', 'bad name'])]).toEqual([
      ['Button', 2],
      ['Card.Header', 1],
    ]);
  });
});

describe('the kit lint', () => {
  const index = tokenIndex(tokens);

  it('finds raw colours and sizes with the token of the same value', () => {
    const css = [
      '.card {',
      '  color: #4f46e5;',
      '  background: rgb(10 20 30);',
      '  padding: 16px 12px;',
      '  border-radius: 6px;',
      '  border: 1px solid var(--color-line);',
      '  margin: var(--space-4);',
      '}',
      '#main { gap: 0; }',
      '/* #ff0000 in a comment',
      '   still a comment #00ff00 */',
      '.x { color: #fff; } // kit-ignore',
    ].join('\n');
    expect(lintKit('src/card.css', css, index)).toEqual([
      { path: 'src/card.css', line: 2, kind: 'colour', value: '#4f46e5', token: 'color.brand' },
      { path: 'src/card.css', line: 3, kind: 'colour', value: 'rgb(10 20 30)', token: null },
      { path: 'src/card.css', line: 4, kind: 'size', value: '16px', token: 'space.4' },
      { path: 'src/card.css', line: 4, kind: 'size', value: '12px', token: null },
      { path: 'src/card.css', line: 5, kind: 'size', value: '6px', token: 'radius.md' },
    ]);
  });

  it('reads style objects in components, and leaves other files alone', () => {
    const tsx = "const s = { fontSize: '1rem', marginTop: 8, color: '#4F46E5' };\n// #123456";
    expect(lintKit('src/a.tsx', tsx, index).map((f) => [f.kind, f.value, f.token])).toEqual([
      ['colour', '#4F46E5', 'color.brand'],
      ['size', '1rem', 'space.4'],
    ]);
    expect(lintKit('src/a.ts', tsx, index)).toEqual([]);
    expect(
      lintKit(
        'tokens.css',
        '/* Design tokens, generated by Orqiva. Do not edit by hand. */\n:root { --x: #fff; }',
        index,
      ),
    ).toEqual([]);
  });
});

describe('the agent rule', () => {
  it('names the components and tokens to use, and the deprecated ones', () => {
    const rule = kitRule(tokens, [
      { name: 'Button', codePath: 'src/ui/Button.tsx', status: 'in_code' },
      { name: 'OldModal', codePath: '', status: 'deprecated' },
    ]);
    expect(rule).toContain('Components: Button (src/ui/Button.tsx).');
    expect(rule).toContain('Deprecated, do not use: OldModal.');
    expect(rule).toContain(
      'Tokens: color.primary #4F46E5; color.brand {color.primary}; space.4 1rem',
    );
    expect(kitRule([], [])).toBe('');
    expect(kitRule(tokens, [], 120)).toHaveLength(120);
  });
});
